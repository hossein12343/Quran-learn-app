import 'quran_seed.dart';

/// Where each of the standard 604-page Uthmani mushaf's pages begins —
/// the same pagination printed mushafs and Quran.com both use (source:
/// api.quran.com's per-verse `page_number` field, walked in Quran order
/// by `tools/fetch_page_boundaries.py`, not guessed). Independent of ayah
/// text, so it works even before [loadFullQuran] finishes.
class PageStart {
  final int page;
  final int surah;
  final int ayah;
  const PageStart(this.page, this.surah, this.ayah);
}

/// One page's actual content — a page can be entirely within one surah,
/// span a surah boundary (the common case: most pages end mid-surah and
/// the next page continues it), or hold several short surahs at once
/// (common in the later, short-surah pages).
class MushafPageContent {
  final int page;
  final List<({Surah surah, List<Ayah> ayat})> segments;
  const MushafPageContent(this.page, this.segments);
}

int get mushafTotalPages => pageStarts.length;

/// Builds a page's content by walking surahs from where it starts to
/// where the *next* page starts (exclusive) — everything in between
/// belongs to this page. Falls back to an empty page (rather than
/// throwing) if [loadFullQuran] hasn't replaced the 4-surah fallback
/// yet and a referenced surah simply isn't loaded — the UI shows a
/// loading state for that, not a crash.
MushafPageContent contentForPage(int page) {
  final start = pageStarts[page - 1];
  final end = page < pageStarts.length ? pageStarts[page] : null;
  final segments = <({Surah surah, List<Ayah> ayat})>[];

  for (var sNum = start.surah; sNum <= (end?.surah ?? 114); sNum++) {
    final matches = surahs.where((s) => s.number == sNum);
    if (matches.isEmpty) continue;
    final surah = matches.first;
    final ayat = surah.ayat.where((a) {
      if (sNum == start.surah && a.number < start.ayah) return false;
      if (end != null && sNum == end.surah && a.number >= end.ayah) {
        return false;
      }
      return true;
    }).toList();
    if (ayat.isNotEmpty) segments.add((surah: surah, ayat: ayat));
  }
  return MushafPageContent(page, segments);
}

